create table if not exists public.bookings (
  id bigint generated by default as identity primary key,
  booking_code text not null unique,
  full_name text not null,
  phone text not null,
  venue_id text not null,
  venue_name text not null,
  booking_date date not null,
  start_time time not null,
  end_time time not null,
  amount integer not null default 0,
  status text not null default 'confirmed' check (status in ('held', 'confirmed', 'cancelled')),
  created_at timestamptz not null default now()
);
create unique index if not exists active_booking_slot on public.bookings (venue_id, booking_date, start_time) where status in ('held', 'confirmed');
alter table public.bookings add column if not exists amount integer not null default 0;
alter table public.bookings enable row level security;
